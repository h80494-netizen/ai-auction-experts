def resolve_region_coords(*texts: str) -> Tuple[float, float, str]:
    """
    입력된 지역명/제목/키워드에서 가장 구체적인 지역명을 찾아 대표 위경도(lat, lng, matched_name)를 반환합니다.
    긴 지명(구체적인 동/지구/구)을 먼저 매칭하여 '서울특별시 양천구 목동' -> '목동' 좌표가 정확히 나오도록 합니다.
    """
    combined = " ".join([str(t or "") for t in texts]).strip()
    if not combined:
        return (37.5400, 126.9900, "서울·수도권")

    # 우선순위: 1) 정확히 일치하는 키, 2) 구체적인 동/지구/시군구(글자 길이 긴 순, 광역시도 제외), 3) 광역시도
    broad_keys = {"서울", "서울시", "서울특별시", "경기", "경기도", "인천", "인천시", "인천광역시", "부산", "부산광역시", "대구", "대구광역시", "대전", "대전광역시", "광주광역시", "전라남도"}

    tokens = [tok.strip() for tok in re.split(r"[\s,·/()\[\]]+", combined) if tok.strip()]
    for tok in reversed(tokens):
        if tok in REGION_CENTER_COORDS and tok not in broad_keys:
            lat, lng = REGION_CENTER_COORDS[tok]
            return (lat, lng, tok)

    specific_keys = sorted(
        [k for k in REGION_CENTER_COORDS.keys() if k not in broad_keys],
        key=lambda x: len(x),
        reverse=True,
    )
    for k in specific_keys:
        if k in combined:
            lat, lng = REGION_CENTER_COORDS[k]
            return (lat, lng, k)

    for k in sorted(broad_keys, key=lambda x: len(x), reverse=True):
        if k in combined:
            lat, lng = REGION_CENTER_COORDS[k]
            return (lat, lng, k)

    return (37.5400, 126.9900, combined)


