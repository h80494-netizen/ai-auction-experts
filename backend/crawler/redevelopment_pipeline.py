def match_auctions_for_project(conn: sqlite3.Connection, project: Dict[str, Any], limit: int = 8) -> List[Dict[str, Any]]:
    """
    map_data.db의 auctions 테이블에서 해당 정비사업 구역(법정동·단지 키워드 또는 반경)에 속하는
    진행 중인 경·공매 물건을 자동 매칭하여 반환합니다.
    """
    cursor = conn.cursor()
    cursor.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='auctions'")
    if not cursor.fetchone():
        return []

    raw_kws = [k.strip() for k in str(project.get("auction_match_keywords", "")).split(",") if k.strip()]
    bjdong = str(project.get("bjdong_name", "")).strip()
    zone_group = str(project.get("zone_group", "")).strip()

    # 시군구/동 핵심 토큰 추출
    dong_tokens = [t.strip() for t in re.split(r"[\s·,/]+", bjdong) if len(t.strip()) >= 2]
    all_tokens = []
    for t in dong_tokens + raw_kws:
        if t and t not in all_tokens and t not in ("서울", "경기", "인천", "서울시", "경기도", "인천시"):
            all_tokens.append(t)

    lat = float(project.get("latitude") or 37.54)
    lng = float(project.get("longitude") or 126.99)

    # 1차: 좌표 반경(약 2.2km 내외) + 주소 키워드 매칭
    lat_delta = 0.022
    lng_delta = 0.026
    cursor.execute('''
        SELECT case_no, sale_type, property_type, address, appraisal_price, min_price,
               min_bid_rate, lat, lng, area_size, sale_date
        FROM auctions
        WHERE lat BETWEEN ? AND ?
          AND lng BETWEEN ? AND ?
        ORDER BY min_bid_rate ASC
        LIMIT 80
    ''', (lat - lat_delta, lat + lat_delta, lng - lng_delta, lng + lng_delta))
    candidates = cursor.fetchall()

    matched = []
    seen_cases = set()

    for row in candidates:
        case_no, sale_type, prop_type, addr, appr, min_p, bid_rate, a_lat, a_lng, area_sz, s_date = row
        if not case_no or case_no in seen_cases:
            continue
        addr_str = str(addr or "")
        score = 0
        for tok in all_tokens:
            if tok in addr_str:
                score += (3 if len(tok) >= 3 else 1)
        if score > 0 or len(matched) < 3:
            seen_cases.add(case_no)
            is_spec = bool(project.get("is_speculative_zone"))
            stage_step = int(project.get("stage_step") or 1)
            if is_spec and stage_step >= 4:
                badge_type = "danger"
                badge_text = "⚠️ 조합설립/시행자지정 완료 — 10년소유·5년거주 또는 금융기관 경매예외 확인 필수 (현금청산 주의)"
            elif is_spec:
                badge_type = "warning"
                badge_text = "🟢 토지거래허가 예외 (경매 낙찰 시 실거주 의무 면제 · 추진위 단계 지위승계 가능)"
            else:
                badge_type = "success"
                badge_text = "✅ 비투기과열지구 — 조합원/토지등소유자 지위승계 가능 (권리산정일·분담금 확인)"

            matched.append({
                "case_no": case_no,
                "sale_type": sale_type or "경매",
                "property_type": prop_type or "아파트",
                "address": addr_str,
                "appraisal_price": appr or 0,
                "min_price": min_p or 0,
                "min_bid_rate": bid_rate or 0,
                "lat": a_lat or lat,
                "lng": a_lng or lng,
                "area_size": area_sz or 0,
                "sale_date": s_date or "",
                "match_score": score,
                "zone_group": zone_group,
                "project_name": project.get("project_name", ""),
                "risk_badge_type": badge_type,
                "risk_badge_text": badge_text,
            })

    matched.sort(key=lambda x: (-x["match_score"], x["min_bid_rate"] or 100))
    return matched[:limit]


